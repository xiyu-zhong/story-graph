import type { Work } from "../../lib/types";

type EventDraft = [
  title: string,
  description: string,
  characterIds: string[],
  locationId?: string,
];
const chapterId = (order: number) => `mortal-${String(order).padStart(2, "0")}`;
function segment(
  order: number,
  title: string,
  arc: string,
  summary: string,
  paragraphs: string[],
  characterIds: string[],
  locationIds: string[],
  events: EventDraft[],
  sourceIds: string[],
  limitation: string,
): Work["chapters"][number] {
  return {
    id: chapterId(order),
    order,
    title,
    arc,
    summary,
    paragraphs,
    characterIds,
    locationIds,
    events: events.map(
      ([title, description, characterIds, locationId], index) => ({
        id: `${chapterId(order)}-e${index + 1}`,
        title,
        description,
        characterIds,
        ...(locationId ? { locationId } : {}),
      }),
    ),
    sourceIds,
    editorialNote: `编辑主线整理，标题为编辑拟定，非原作章名；${limitation}未逐章核对原文，不提供原作章节定位。`,
  };
}
function person(
  id: string,
  name: string,
  role: string,
  faction: string,
  description: string,
  firstChapter: number,
  aliases: string[] = [],
): Work["characters"][number] {
  return { id, name, aliases, role, faction, description, firstChapter };
}
function relation(
  id: string,
  source: string,
  target: string,
  label: string,
  type: Work["relationships"][number]["type"],
  orders: number[],
  description: string,
): Work["relationships"][number] {
  return {
    id,
    source,
    target,
    label,
    type,
    description,
    chapterIds: orders.map(chapterId),
  };
}
function place(
  id: string,
  name: string,
  region: string,
  description: string,
  x: number,
  y: number,
  kind: Work["locations"][number]["kind"],
): Work["locations"][number] {
  return { id, name, region, description, x, y, kind };
}

