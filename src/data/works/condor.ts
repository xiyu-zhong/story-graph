const chapterId = (order: number) => `condor-${String(order).padStart(2, "0")}`;
const editionNote =
  "以1970—80年代修订版四十回为框架，回目据远流修订版出版目录核对；情节为依据二手梗概与已知叙事顺序撰写的原创导读，跨回过渡有所压缩，未对授权正文逐页逐回校勘。事件编号不是原文段落定位。";
type EventSeed = [
  title: string,
  description: string,
  characterIds: string[],
  locationId: string,
];
function chapter(
  order: number,
  title: string,
  summary: string,
  paragraphs: string[],
  scenes: EventSeed[],
  note = "",
): Chapter {
  const events: StoryEvent[] = scenes.map(
    ([title, description, characterIds, locationId], index) => ({
      id: `${chapterId(order)}-e${index + 1}`,
      title,
      description,
      characterIds,
      locationId,
    }),
  );
  return {
    id: chapterId(order),
    unitType: "chapter",
    order,
    title,
    arc:
      order <= 6
        ? "风雪遗孤与大漠成长"
        : order <= 15
          ? "初入江湖与身世之争"
          : order <= 22
            ? "桃岛争经与海上患难"
            : order <= 31
              ? "江南风波与南行求医"
              : order <= 35
                ? "师门血案与真相"
                : "西征、抉择与英雄之问",
    summary,
    paragraphs,
    events,
    characterIds: [...new Set(events.flatMap((event) => event.characterIds))],
    locationIds: [...new Set(events.map((event) => event.locationId!))],
    sourceIds: [
      "condor-ylib",
      "condor-wiki",
      "condor-chapter-commentary",
      ...(order >= 34 && order <= 36 ? ["condor-yang-kang"] : []),
    ],
    originalRange: `第${order}回 ${title}`,
    editorialNote: editionNote + (note ? ` ${note}` : ""),
  };
}

